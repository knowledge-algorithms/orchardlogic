"""Loader, validator and identity helpers for ``treedb_fixture_v1`` files.

Contract: ``docs/CONTRACTS.md`` (INV-n). Format: ``fixtures/SCHEMA.md``.
No SQL and no DuckDB here: this module only reads JSON and checks Z-arrays.
"""

from __future__ import annotations

import hashlib
import json
import uuid
from pathlib import Path
from typing import Any, Mapping, Sequence

import numpy as np
from scipy.cluster.hierarchy import is_valid_linkage

FORMAT = "treedb_fixture_v1"

# INV-5: namespace for the deterministic item_id -> UUID rule.
# Equal to uuid.uuid5(uuid.NAMESPACE_URL, "urn:treedb:fixture:v1").
FIXTURE_NAMESPACE = uuid.UUID("298a2a1d-c249-5e3d-90b2-b713abff5aa4")

COHORT_KINDS = frozenset(
    {
        "whole", "root_lca", "stem", "single", "siblings",
        "random_seeded", "top_label", "with_missing",
    }
)
MUTATION_OPS = frozenset({"detach", "attach"})


class FixtureError(ValueError):
    """Raised when a fixture file violates ``treedb_fixture_v1``."""


# ---------------------------------------------------------------------------
# Identity helpers (INV-3, INV-5, INV-22)
# ---------------------------------------------------------------------------

def canonical_json(value: Any) -> str:
    """Same canonical JSON as ``orchard.identity.canonical_json``."""
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def member_key(item_ids: Sequence[str]) -> str:
    """``member_<sha256(canonical_json(sorted(item_ids)))>`` (INV-3).

    Content key of a node's descendant set. Not a mutable node key.
    """
    members = sorted(item_ids)
    if len(members) != len(set(members)):
        raise FixtureError("member_key: item_ids must be unique")
    digest = hashlib.sha256(canonical_json(members).encode("utf-8")).hexdigest()
    return f"member_{digest}"


def item_uuid(item_id: str) -> uuid.UUID:
    """UUID the PostgreSQL harness uses as ``doc_id`` / leaf ``node_id`` (INV-5)."""
    return uuid.uuid5(FIXTURE_NAMESPACE, f"item:{item_id}")


def tree_uuid(fixture_name: str, cultivar: str) -> uuid.UUID:
    """UUID for a cultivar's ``tree_registry.id`` in the harness (INV-5)."""
    return uuid.uuid5(FIXTURE_NAMESPACE, f"tree:{fixture_name}:{cultivar}")


def branch_uuid(fixture_name: str, cultivar: str, node_member_key: str) -> uuid.UUID:
    """UUID for an internal node's ``tree_z`` doc_id (the branch id) (INV-5).

    The root's UUID is generated by ``v_tree_map`` in PostgreSQL (OD-3) and is
    not controlled by this rule.
    """
    return uuid.uuid5(
        FIXTURE_NAMESPACE, f"node:{fixture_name}:{cultivar}:{node_member_key}"
    )


def structural_key(tree_name: str, item_ids: Sequence[str]) -> str:
    """Comparison key for a node across backends (INV-22).

    ``<tree_name>#<member_key(items)>``. The sorted item list is the identity;
    the hash only encodes it.
    """
    return f"{tree_name}#{member_key(item_ids)}"


# ---------------------------------------------------------------------------
# Z helpers
# ---------------------------------------------------------------------------

def node_members(
    z: Sequence[Sequence[float]], item_ids: Sequence[str]
) -> dict[int, tuple[str, ...]]:
    """SciPy node index -> sorted descendant item_ids (INV-8)."""
    n = len(item_ids)
    members: dict[int, tuple[str, ...]] = {i: (item_ids[i],) for i in range(n)}
    for r, row in enumerate(z):
        left, right = int(row[0]), int(row[1])
        members[n + r] = tuple(sorted(members[left] + members[right]))
    return members


def node_keys(z: Sequence[Sequence[float]], item_ids: Sequence[str]) -> dict[int, str]:
    """SciPy node index -> ``member_`` key (the fixture's source node key)."""
    return {i: member_key(m) for i, m in node_members(z, item_ids).items()}


def cultivar_item_ids(fixture: Mapping[str, Any], cultivar: Mapping[str, Any]) -> list[str]:
    """Ordered leaf item_ids of a cultivar (defaults to the fixture's)."""
    return list(cultivar.get("item_ids", fixture["item_ids"]))


# ---------------------------------------------------------------------------
# Loader / validator
# ---------------------------------------------------------------------------

def load_fixture(path: str | Path) -> dict[str, Any]:
    """Read a fixture file and validate it. Returns the parsed dict."""
    with open(path, encoding="utf-8") as fh:
        fixture = json.load(fh)
    validate_fixture(fixture)
    return fixture


def _require(cond: bool, msg: str) -> None:
    if not cond:
        raise FixtureError(msg)


def _validate_item_ids(ids: Any, where: str) -> None:
    _require(isinstance(ids, list) and bool(ids), f"{where}: item_ids must be a non-empty list")
    _require(
        all(isinstance(i, str) and i and i.strip() == i for i in ids),
        f"{where}: item_ids must be non-empty strings without edge whitespace",
    )
    _require(len(ids) == len(set(ids)), f"{where}: item_ids must be unique")


def validate_z(z: Any, n: int, where: str) -> None:
    """INV-9, INV-10: shape, finiteness and SciPy validity."""
    arr = np.asarray(z, dtype=float)
    _require(arr.shape == (n - 1, 4), f"{where}: Z must have shape ({n - 1}, 4)")
    _require(bool(np.isfinite(arr).all()), f"{where}: Z has non-finite values")
    _require(bool((arr[:, 2] >= 0).all()), f"{where}: Z has negative distances")
    _require(bool(is_valid_linkage(arr)), f"{where}: Z fails scipy is_valid_linkage")


def validate_fixture(fixture: Mapping[str, Any]) -> None:
    """Raise ``FixtureError`` when ``fixture`` is not a valid treedb_fixture_v1."""
    _require(fixture.get("format") == FORMAT, f"format must be {FORMAT!r}")
    name = fixture.get("name")
    _require(isinstance(name, str) and bool(name), "name is required")
    _validate_item_ids(fixture.get("item_ids"), "fixture")
    all_items = set(fixture["item_ids"])

    cultivars = fixture.get("cultivars")
    _require(isinstance(cultivars, list) and bool(cultivars), "cultivars must be a non-empty list")
    keys_by_cultivar: dict[str, set[str]] = {}
    for cv in cultivars:
        cname = cv.get("name")
        _require(isinstance(cname, str) and bool(cname), "cultivar name is required")
        _require(cname not in keys_by_cultivar, f"duplicate cultivar {cname!r}")
        where = f"cultivar {cname!r}"
        ids = cultivar_item_ids(fixture, cv)
        _validate_item_ids(ids, where)
        _require(set(ids) <= all_items, f"{where}: item_ids not in fixture item_ids")
        _require(len(ids) >= 2, f"{where}: needs at least 2 leaves")
        validate_z(cv.get("z"), len(ids), where)
        keys = set(node_keys(cv["z"], ids).values())
        keys_by_cultivar[cname] = keys
        for set_name, labels in cv.get("label_sets", {}).items():
            bad = set(labels) - keys
            _require(not bad, f"{where}: label set {set_name!r} has unknown node keys")
        bad = set(cv.get("cards", {})) - keys
        _require(not bad, f"{where}: cards have unknown node keys")

    cases = fixture.get("cases", {})
    names: set[str] = set()

    def new_name(case: Mapping[str, Any]) -> str:
        _require(isinstance(case.get("name"), str), "case name is required")
        _require(case["name"] not in names, f"duplicate case name {case['name']!r}")
        names.add(case["name"])
        return case["name"]

    for co in cases.get("cohorts", []):
        cname = new_name(co)
        _require(co.get("kind") in COHORT_KINDS, f"cohort {cname!r}: bad kind")
        _validate_item_ids(co.get("item_ids"), f"cohort {cname!r}")
        _require(set(co["item_ids"]) <= all_items, f"cohort {cname!r}: unknown items")
        if "cultivar" in co:
            _require(co["cultivar"] in keys_by_cultivar, f"cohort {cname!r}: unknown cultivar")
    for ep in cases.get("entry_points", []):
        ename = new_name(ep)
        _require(ep.get("cultivar") in keys_by_cultivar, f"entry {ename!r}: unknown cultivar")
        _require(
            ep.get("node_key") in keys_by_cultivar[ep["cultivar"]],
            f"entry {ename!r}: node_key not in cultivar",
        )
    for mu in cases.get("mutations", []):
        mname = new_name(mu)
        _require(mu.get("cultivar") in keys_by_cultivar, f"mutation {mname!r}: unknown cultivar")
        _require(mu.get("expect") in ("ok", "error"), f"mutation {mname!r}: bad expect")
        _require(isinstance(mu.get("steps"), list) and bool(mu["steps"]), f"mutation {mname!r}: no steps")
        for step in mu["steps"]:
            _require(step.get("op") in MUTATION_OPS, f"mutation {mname!r}: bad op")
